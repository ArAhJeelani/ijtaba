"""Build a public-only TypeScript catalog from approved SQLite records."""
import json
from pathlib import Path
from tempfile import NamedTemporaryFile

from records import COLLECTIONS, SourceRecord


def publish(db, destination):
    entries = []
    for row in db.execute("""SELECT c.* FROM candidates c WHERE c.status = 'approved'
                         AND EXISTS (SELECT 1 FROM history h WHERE h.candidate_id = c.id
                         AND h.action = 'approve' AND h.payload = c.payload
                         AND h.id = (SELECT MAX(id) FROM history WHERE candidate_id = c.id))
                         ORDER BY c.id"""):
        record = SourceRecord.model_validate_json(row["payload"])
        if record.uncertainties:
            raise ValueError(f"{record.id} still has unresolved review flags.")
        entry = {
            "id": record.id,
            "title": record.title,
            "arabic": record.arabic,
            "translation": record.translation or "",
            "category": record.categories[0],
            "categories": record.categories,
            "reference": f"{COLLECTIONS[record.collection]} {record.reference}",
            "url": record.source_url,
            "context": record.context,
        }
        if record.translation_attribution:
            entry["translationAttribution"] = record.translation_attribution
        if record.transliteration:
            entry["transliteration"] = record.transliteration
        entries.append(entry)
    content = ("// Generated by research/manage.py publish.\n"
               'import type { Dua } from "./duas";\n\n'
               "export const approvedDuas: Dua[] = "
               + json.dumps(entries, ensure_ascii=False, indent=2) + ";\n")
    temporary = None
    try:
        with NamedTemporaryFile(mode="w", encoding="utf-8", newline="\n",
                                dir=destination.parent, delete=False) as output:
            temporary = Path(output.name)
            output.write(content)
        temporary.replace(destination)
    finally:
        if temporary is not None:
            temporary.unlink(missing_ok=True)
    return len(entries)
